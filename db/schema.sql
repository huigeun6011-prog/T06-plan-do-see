CREATE TABLE IF NOT EXISTS game_character (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name       text NOT NULL CHECK (name <> '') UNIQUE,   -- job name only, never a nickname
  sort_order int  NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Recurring registrations. Versioned: root_id = id of the first version.
CREATE TABLE IF NOT EXISTS entry (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  root_id       bigint NOT NULL REFERENCES entry(id),
  character_id  bigint REFERENCES game_character(id),     -- NULL = account-level
  title         text   NOT NULL CHECK (title <> ''),
  period_kind   text   NOT NULL CHECK (period_kind IN ('weekly','monthly')),
  clear_minutes int    NOT NULL CHECK (clear_minutes >= 1), -- minutes per unit
  reward_meso   bigint NOT NULL DEFAULT 0 CHECK (reward_meso >= 0),
  party_size    int    NOT NULL DEFAULT 1 CHECK (party_size >= 1),
  doping        text   NOT NULL DEFAULT 'base',
  memo          text   NOT NULL DEFAULT '',
  target_count  int    NOT NULL DEFAULT 1 CHECK (target_count >= 1),
  tags          text[] NOT NULL DEFAULT '{}',
  sort_order    int    NOT NULL DEFAULT 0,
  use_yn        char(1) NOT NULL DEFAULT 'Y' CHECK (use_yn IN ('Y','N')),
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS entry_one_current  ON entry (root_id) WHERE use_yn = 'Y';
CREATE UNIQUE INDEX IF NOT EXISTS entry_one_per_title ON entry (COALESCE(character_id, 0), title) WHERE use_yn = 'Y';

-- Plans: weekly, monthly or event. Versioned the same way.
CREATE TABLE IF NOT EXISTS plan (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  root_id          bigint NOT NULL REFERENCES plan(id),
  period_kind      text NOT NULL CHECK (period_kind IN ('weekly','monthly','event')),
  title            text NOT NULL DEFAULT '',
  starts_at        timestamptz NOT NULL,                 -- clean KST boundary
  ends_at          timestamptz NOT NULL,                 -- exclusive
  priority         smallint NOT NULL DEFAULT 2 CHECK (priority BETWEEN 1 AND 3), -- 1 = highest
  success_criteria text NOT NULL CHECK (success_criteria <> ''),
  expected_minutes int  NOT NULL DEFAULT 0 CHECK (expected_minutes >= 0),
  use_yn           char(1) NOT NULL DEFAULT 'Y' CHECK (use_yn IN ('Y','N')),
  created_at       timestamptz NOT NULL DEFAULT now(),
  CHECK (ends_at > starts_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS plan_one_current ON plan (root_id) WHERE use_yn = 'Y';
CREATE UNIQUE INDEX IF NOT EXISTS plan_one_per_period ON plan (period_kind, starts_at)
  WHERE use_yn = 'Y' AND period_kind <> 'event';

-- Todos: edited in place; delete = use_yn 'N'. plan_id / entry_id always hold the ROOT id.
CREATE TABLE IF NOT EXISTS todo (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  plan_id          bigint NOT NULL REFERENCES plan(id),
  entry_id         bigint REFERENCES entry(id),          -- NULL for hand-made todos
  source_plan_id   bigint REFERENCES plan(id),           -- set when this todo is a retro improvement
  title            text NOT NULL CHECK (title <> ''),
  note             text NOT NULL DEFAULT '',
  character_id     bigint REFERENCES game_character(id),
  due_at           timestamptz NOT NULL,                 -- clean boundary; generated = plan.ends_at
  priority         smallint NOT NULL DEFAULT 2 CHECK (priority BETWEEN 1 AND 3),
  tags             text[] NOT NULL DEFAULT '{}',
  expected_minutes int NOT NULL DEFAULT 0 CHECK (expected_minutes >= 0), -- per unit x target
  target_count     int NOT NULL DEFAULT 1 CHECK (target_count >= 1),
  miss_reason      text CHECK (miss_reason IS NULL OR (miss_reason <> '' AND char_length(miss_reason) <= 200)),
  use_yn           char(1) NOT NULL DEFAULT 'Y' CHECK (use_yn IN ('Y','N')),
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (plan_id, entry_id)                              -- idempotent generation; NULL entry_id exempt
);
CREATE UNIQUE INDEX IF NOT EXISTS todo_one_improvement ON todo (source_plan_id)
  WHERE source_plan_id IS NOT NULL AND use_yn = 'Y';
CREATE INDEX IF NOT EXISTS todo_plan_idx ON todo (plan_id);

-- Run records: one row per todo per Seoul day. Edited in place; delete = use_yn 'N'.
CREATE TABLE IF NOT EXISTS run_record (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  todo_id        bigint NOT NULL REFERENCES todo(id),
  run_date       date   NOT NULL,                        -- Seoul date, supplied by the app
  units          int    NOT NULL DEFAULT 1 CHECK (units >= 1),  -- that day's count, set not added
  started_at     timestamptz,
  ended_at       timestamptz,
  actual_minutes int CHECK (actual_minutes >= 0),        -- NULL = not entered
  done           boolean NOT NULL DEFAULT true,          -- false = un-completed, row and minutes kept
  use_yn         char(1) NOT NULL DEFAULT 'Y' CHECK (use_yn IN ('Y','N')),
  created_at     timestamptz NOT NULL DEFAULT now(),
  CHECK (started_at IS NULL OR ended_at IS NULL OR ended_at >= started_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS run_one_per_day ON run_record (todo_id, run_date) WHERE use_yn = 'Y';

-- Single definition of "done / actual / blocked" for every read.
CREATE OR REPLACE VIEW todo_state AS
SELECT t.*,
       COALESCE(r.done_n, 0)      AS done_n,
       COALESCE(r.actual, 0)      AS actual_minutes,
       (t.miss_reason IS NOT NULL) AS blocked,
       COALESCE(r.done_n, 0) >= t.target_count AS is_done
FROM todo t
LEFT JOIN (
  SELECT todo_id,
         COALESCE(sum(units) FILTER (WHERE done), 0)::int AS done_n,
         COALESCE(sum(actual_minutes) FILTER (WHERE done), 0)::int AS actual
  FROM run_record WHERE use_yn = 'Y' GROUP BY todo_id
) r ON r.todo_id = t.id
WHERE t.use_yn = 'Y';
